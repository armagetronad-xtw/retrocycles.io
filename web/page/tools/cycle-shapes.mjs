// Writes src/components/settings/cycleShapes.ts: the stock light cycle (models/cycle_*.mod) seen
// from the side, from behind and from above, in metres, for the camera rig. Placed as
// gCycle::Render places it (the parts at half scale, 1.5 model units back, the rear wheel's axle
// .73 up, the front's 1.84 ahead and .43 up), so the drawing is the game's own cycle at its size.
// Each projected triangle is turned counter-clockwise, so one path filled nonzero is their union.
//   node tools/cycle-shapes.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const models = join(here, "../../../models");

function load(name, [ox, oy, oz]) {
  const v = [];
  const f = [];
  for (const line of readFileSync(join(models, name), "utf8").split(/\r?\n/)) {
    const p = line.trim().split(/\s+/);
    if (p[0] === "v") v[Number(p[1])] = [Number(p[2]), Number(p[3]), Number(p[4])];
    if (p[0] === "f") f.push([Number(p[1]), Number(p[2]), Number(p[3])]);
  }
  // model units to metres: the part's offset, 1.5 back, half scale
  const at = (i) => [(v[i][0] + ox - 1.5) * 0.5, (v[i][1] + oy) * 0.5, (v[i][2] + oz) * 0.5];
  return f.map((t) => t.map(at));
}

const body = load("cycle_body.mod", [0, 0, 0]);
const rear = load("cycle_rear.mod", [0, 0, 0.73]);
const front = load("cycle_front.mod", [1.84, 0, 0.43]);
const all = [...body, ...rear, ...front];

const cm = (n) => Math.round(n * 100) / 100;
const r = (n) => String(cm(n)).replace(/^(-?)0\./, "$1.");

// one path of the triangles seen along an axis: u, v pick the coordinates (0 x, 1 y, 2 z)
function path(tris, u, v) {
  let out = "";
  for (const t of tris) {
    let p = t.map((q) => [q[u], q[v]]);
    const area = (p[1][0] - p[0][0]) * (p[2][1] - p[0][1]) - (p[2][0] - p[0][0]) * (p[1][1] - p[0][1]);
    if (Math.abs(area) < 1e-4) continue; // edge-on, or too small to show
    if (area < 0) p = [p[0], p[2], p[1]];
    out += "M" + p.map((q) => r(q[0]) + " " + r(q[1])).join("L") + "Z";
  }
  return out;
}

function bounds(tris, u, v) {
  const pts = tris.flat();
  const b = (i) => [cm(Math.min(...pts.map((q) => q[i]))), cm(Math.max(...pts.map((q) => q[i])))];
  return { u: b(u), v: b(v) };
}

// a wheel seen from the side: its centre and radius
function wheel(tris) {
  const b = bounds(tris, 0, 2);
  return { cx: cm((b.u[0] + b.u[1]) / 2), cy: cm((b.v[0] + b.v[1]) / 2), r: cm((b.u[1] - b.u[0] + b.v[1] - b.v[0]) / 4) };
}

const list = (a) => "[" + a.join(", ") + "]";
const side = bounds(all, 0, 2);
const back = bounds(all, 1, 2);
const top = bounds(all, 0, 1);
const tyre = bounds(rear, 1, 2);
const wheels = [wheel(rear), wheel(front)];

const ts = `// generated by tools/cycle-shapes.mjs from models/cycle_*.mod: do not edit
// the stock light cycle in metres where the game puts it: its position at 0 (the nose a little
// ahead of it), the floor at 0. u is the drawing's x, v its y

// from its left: forward, up; the wheels as circles
export const CYCLE_SIDE = {
  body: "${path(body, 0, 2)}",
  wheels: [${wheels.map((w) => `{ cx: ${w.cx}, cy: ${w.cy}, r: ${w.r} }`).join(", ")}],
  u: ${list(side.u)},
  v: ${list(side.v)}
} as const;

// from behind: to its left, up; the rear tyre, the nearest part, as a box
export const CYCLE_REAR = {
  body: "${path(all, 1, 2)}",
  tyre: { u: ${list(tyre.u)}, v: ${list(tyre.v)} },
  u: ${list(back.u)},
  v: ${list(back.v)}
} as const;

// from above: forward, to its left
export const CYCLE_TOP = {
  body: "${path(all, 0, 1)}",
  u: ${list(top.u)},
  v: ${list(top.v)}
} as const;
`;
writeFileSync(join(here, "../src/components/settings/cycleShapes.ts"), ts);
