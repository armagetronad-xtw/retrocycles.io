// Noto Sans KR / JP / SC / TC for the chat overlay: Google Fonts' own
// unicode-range slices of the variable fonts (weight 100-900), self-hosted so the page asks
// no font CDN (COEP, privacy), and each slice is fetched only when a character in it is on
// screen. Writes public/fonts/cjk/<kr|jp|sc|tc>/<n>.woff2 and public/fonts/cjk/faces.css. The
// faces sheet (about 400 KB) is not in the page's bundle: chat/text.ts links it the first time
// a CJK character is shown, so a first visit pays nothing for it.
//
//   node tools/cjk-fonts.mjs        (from web/page; about 18 MB, 457 files)
//
// Run it again to take a newer version; the slices are unmodified (SIL OFL 1.1,
// public/fonts/NOTICE.txt).
import { mkdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const FAMILIES = [
  ["kr", "Noto Sans KR"],
  ["jp", "Noto Sans JP"],
  ["sc", "Noto Sans SC"],
  ["tc", "Noto Sans TC"]
];
// a current browser's user agent, so the API answers with woff2 and unicode-range slices
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36";

async function fetchOk(url, as) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return as === "text" ? res.text() : Buffer.from(await res.arrayBuffer());
}

let css = `/* Generated by tools/cjk-fonts.mjs: do not edit. Noto Sans KR / JP / SC / TC, Google
   Fonts' unicode-range slices of the variable fonts (weight 100-900), self-hosted; a slice is
   fetched only when a character in it is drawn. SIL OFL 1.1, public/fonts/NOTICE.txt. Used by
   the chat overlay for what players write (chat.css, by the line's lang); linked by
   chat/text.ts the first time it is needed. */\n`;
let files = 0;
let bytes = 0;

for (const [dir, family] of FAMILIES) {
  const sheet = await fetchOk(`https://fonts.googleapis.com/css2?family=${family.replace(/ /g, "+")}:wght@400;600&display=swap`, "text");
  // the API lists each slice once per weight asked for, with the same variable file
  const slices = new Map();
  for (const face of sheet.matchAll(/@font-face\s*{([^}]*)}/g)) {
    const url = /url\((https:[^)]+\.woff2)\)/.exec(face[1])?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(face[1])?.[1];
    if (url && range && !slices.has(url)) slices.set(url, range.trim());
  }
  const out = `${ROOT}public/fonts/cjk/${dir}`;
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  let n = 0;
  const list = [...slices];
  // a few at a time
  for (let i = 0; i < list.length; i += 8) {
    await Promise.all(
      list.slice(i, i + 8).map(async ([url, range], k) => {
        const index = i + k;
        const data = await fetchOk(url, "buffer");
        await writeFile(`${out}/${index}.woff2`, data);
        bytes += data.length;
        files++;
        n++;
        slices.set(url, { range, index });
      })
    );
  }
  for (const { range, index } of slices.values()) {
    css += `@font-face{font-family:"${family}";font-style:normal;font-weight:100 900;font-display:swap;src:url("${dir}/${index}.woff2") format("woff2");unicode-range:${range};}\n`;
  }
  console.log(`${family}: ${n} slices`);
}

await writeFile(`${ROOT}public/fonts/cjk/faces.css`, css);
console.log(`${files} files, ${(bytes / 1048576).toFixed(1)} MB; public/fonts/cjk/faces.css written`);
